/// Look up a glyph by ASCII character.  Unknown / non-ASCII → space.
fn glyph_for(c: char) -> &'static Glyph {
    let idx = (c as u32).wrapping_sub(32) as usize;
    GLYPHS.get(idx).unwrap_or(&GLYPHS[0])
}

/// Advance width of a character in Hershey grid units.
pub fn char_advance(c: char) -> f64 {
    let g = glyph_for(c);
    g.1 as f64
}

/// Total advance width of a string in Hershey grid units.
pub fn text_advance(text: &str) -> f64 {
    text.chars().map(char_advance).sum()
}

/// Tessellate one character into stroke polylines at `scale` (grid-unit → world-unit).
/// `origin` is the [x, y] pen position (left edge, baseline).
/// Returns a list of polylines (each polyline is a list of [x, y] points).
pub fn char_strokes(c: char, origin: [f64; 2], scale: f64) -> Vec<Vec<[f64; 2]>> {
    let glyph = glyph_for(c);
    let strokes = glyph.2;
    if strokes.is_empty() {
        return Vec::new();
    }

    let mut polys: Vec<Vec<[f64; 2]>> = Vec::new();
    let mut current: Vec<[f64; 2]> = Vec::new();
    let mut pen_down = false;

    for &(gx, gy) in strokes {
        if gx == PEN_UP {
            // Flush current contour.
            if current.len() >= 2 {
                polys.push(std::mem::take(&mut current));
            } else {
                current.clear();
            }
            pen_down = false;
        } else {
            let x = origin[0] + gx as f64 * scale;
            let y = origin[1] + gy as f64 * scale;
            if !pen_down {
                // First point of new contour — always add as start.
                current.push([x, y]);
                pen_down = true;
            } else {
                current.push([x, y]);
            }
        }
    }
    // Flush final contour.
    if current.len() >= 2 {
        polys.push(current);
    }
    polys
}

/// Tessellate a text string into stroke polylines.
///
/// - `origin`: world-space [x, y] of the left baseline corner.
/// - `height`: cap height in world units (the `height` stored on the annotation).
///
/// Returns: a flat list of polylines, each polyline being a `Vec<[f64; 2]>`.
pub fn text_strokes(text: &str, origin: [f64; 2], height: f64) -> Vec<Vec<[f64; 2]>> {
    let scale = height / GRID_CAP;
    let mut polys = Vec::new();
    let mut pen_x = origin[0];

    for c in text.chars() {
        let glyph = glyph_for(c);
        // Apply left bearing (left_bearing unused in current glyphs, all 0).
        let char_polys = char_strokes(c, [pen_x, origin[1]], scale);
        polys.extend(char_polys);
        pen_x += glyph.1 as f64 * scale;
    }
    polys
}

/// Total text width in world units.
pub fn text_width(text: &str, height: f64) -> f64 {
    let scale = height / GRID_CAP;
    text_advance(text) * scale
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn space_has_no_strokes() {
        let s = text_strokes(" ", [0.0, 0.0], 1.0);
        assert!(s.is_empty(), "space should produce no strokes");
    }

    #[test]
    fn letter_i_produces_strokes() {
        let s = char_strokes('I', [0.0, 0.0], 1.0);
        // 'I' is a single vertical stroke.
        assert!(!s.is_empty(), "I should have at least one stroke");
        assert!(s[0].len() >= 2, "stroke must have ≥ 2 points");
    }

    #[test]
    fn letter_a_capital_stroke_count() {
        let s = char_strokes('A', [0.0, 0.0], 1.0);
        // A has 2 polylines: the two legs (one V stroke) and the crossbar.
        assert!(s.len() >= 2, "A should have ≥2 strokes, got {}", s.len());
    }

    #[test]
    fn text_width_scales_with_height() {
        let w1 = text_width("HELLO", 1.0);
        let w2 = text_width("HELLO", 2.0);
        assert!((w2 - 2.0 * w1).abs() < 1e-9, "width should double with doubled height");
        assert!(w1 > 0.0, "text width must be positive");
    }

    #[test]
    fn height_scaling_correct() {
        // At height=1.0, cap height = 1.0 world unit.
        // The grid Y for cap = GRID_CAP, so scale = 1.0/GRID_CAP.
        // A point at glyph y=GRID_CAP should map to world y = 1.0.
        let scale = 1.0 / GRID_CAP;
        let top = GRID_CAP * scale;
        assert!((top - 1.0).abs() < 1e-12);
    }

    #[test]
    fn hello_text_produces_strokes() {
        let strokes = text_strokes("HELLO", [0.0, 0.0], 1.0);
        assert!(!strokes.is_empty(), "HELLO must produce strokes");
        // Should produce at least one stroke per letter (H, E, L, L, O).
        assert!(strokes.len() >= 5, "HELLO ≥5 strokes, got {}", strokes.len());
    }

    #[test]
    fn pen_up_splits_strokes() {
        // 'H' has 3 strokes: left leg, crossbar, right leg.
        let s = char_strokes('H', [0.0, 0.0], 1.0);
        assert_eq!(s.len(), 3, "H should have 3 strokes, got {}", s.len());
    }

    #[test]
    fn stroke_points_at_correct_height() {
        let h = 2.5;
        // text_strokes applies the height/GRID_CAP scale internally.
        let s = text_strokes("I", [0.0, 0.0], h);
        assert!(!s.is_empty());
        // The topmost point of 'I' (vertical from y=0 to y=GRID_CAP on grid)
        // should be at y = h = cap height in world units.
        let max_y = s.iter().flat_map(|p| p.iter()).map(|p| p[1]).fold(f64::NEG_INFINITY, f64::max);
        assert!((max_y - h).abs() < 1e-9, "cap height mismatch: {max_y} ≠ {h}");
    }

    #[test]
    fn all_printable_ascii_have_glyphs() {
        // Ensure every printable ASCII returns a glyph (even if it's just space).
        for c in (32u8..=126u8).map(|b| b as char) {
            let g = glyph_for(c);
            // advance must be > 0 (even space is 8).
            assert!(g.1 > 0, "char {:?} has zero advance", c);
        }
    }
}
