//! Embedded single-stroke (Hershey simplex) vector font.
//!
//! Glyphs cover ASCII 32–126.  Each glyph is stored as a compact byte array:
//!   - First byte: left-bearing offset (signed i8, added as −left_bearing to
//!     normalize the glyph so its left edge starts at x=0).
//!   - Second byte: right-bearing / advance width (u8).
//!   - Remaining bytes: stroke data in pairs (x, y), with x = i8::MIN used as
//!     a pen-up (move) marker.  Coordinates are on a −12..12 grid; the cap
//!     height (ascender) is 9 units.
//!
//! `text_strokes(text, height)` returns world-space line segments (polylines)
//! scaled so that cap height == `height` meters.  Each polyline is a
//! `Vec<[f64; 2]>` (2-D; callers handle Z / projection).

/// Pen-up marker: X value that signals a new contour start (move without draw).
const PEN_UP: i8 = i8::MIN;

/// One glyph: (left_bearing, advance_width, stroke_data).
/// `stroke_data` is pairs of (i8, i8); PEN_UP in the x field means "lift pen".
type Glyph = (i8, u8, &'static [(i8, i8)]);

/// Scale divisor: the coordinate grid half-range.  Cap height = 9 units on
/// a grid where Y=9 is the cap line and Y=0 is the baseline.
pub const GRID_CAP: f64 = 9.0;

